import AppKit
import ImageIO

/// The clipboard's advertised representations are capabilities, not app identity.
/// Never dereference text, file URLs, remote URLs or application-specific metadata.
enum ScreenshotClipboardImage {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let automatic = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let formats: [NSPasteboard.PasteboardType] = [.png, .tiff,
        .init("public.jpeg"), .init("public.heic")]
    static let maximumBytes = 64 * 1024 * 1024
    static let maximumPixels = 64 * 1024 * 1024

    static func png(from entries: [NSPasteboardItem], maximumBytes: Int = maximumBytes) -> Data? {
        guard entries.count == 1, let entry = entries.first else { return nil }
        let types = Set(entry.types)
        guard !types.contains(concealed), !types.contains(automatic) else { return nil }
        for format in formats where types.contains(format) {
            guard let data = entry.data(forType: format), !data.isEmpty, data.count <= maximumBytes,
                  let source = CGImageSourceCreateWithData(data as CFData,
                      [kCGImageSourceShouldCache: false] as CFDictionary),
                  CGImageSourceGetCount(source) == 1,
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? NSNumber,
                  let height = properties[kCGImagePropertyPixelHeight] as? NSNumber,
                  permittedDimensions(width: width.intValue, height: height.intValue),
                  let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                      kCGImageSourceCreateThumbnailFromImageAlways: true,
                      kCGImageSourceCreateThumbnailWithTransform: true,
                      kCGImageSourceThumbnailMaxPixelSize: max(width.intValue, height.intValue),
                      kCGImageSourceShouldCache: false] as CFDictionary),
                  let png = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]),
                  png.count <= maximumBytes else { continue }
            return png
        }
        return nil
    }

    static func permittedDimensions(width: Int, height: Int) -> Bool {
        width > 0 && height > 0 && width <= 32768 && height <= 32768
            && width <= maximumPixels / height
    }
}

/// A transient image must survive two polls of the same clipboard generation.
/// Seed from the current generation so enabling/restarting never imports history.
struct ScreenshotClipboardSampler {
    private var handled: Int
    private var pendingTransient: Int?
    init(changeCount: Int) { handled = changeCount }
    mutating func shouldRead(changeCount: Int, transient: Bool) -> Bool {
        guard changeCount != handled else { pendingTransient = nil; return false }
        if transient && pendingTransient != changeCount {
            pendingTransient = changeCount
            return false
        }
        pendingTransient = nil
        handled = changeCount
        return true
    }
}
